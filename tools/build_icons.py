"""Build the icon set from Not Boring Icons (https://www.notboringicons.com).

Reads figma-plugin/nbi-icons/map.json + raw/*.svg (fetched by tools/nbi_fetch.py) and writes:
  site/icons.js                    inline icon set + drop-in replacement for lucide.createIcons()
  figma-plugin/nbi-icons/icons.json  sanitised SVGs keyed by Headroom icon name (for the Figma plugin)
Headroom keeps its own icon names (Lucide-style) so no page markup changes; each maps to a Not Boring Icons name.
"""
import json, pathlib, re

ROOT = pathlib.Path(__file__).resolve().parent.parent
NB = ROOT / "figma-plugin" / "nbi-icons"
m = json.loads((NB / "map.json").read_text(encoding="utf-8"))
mapping = {k: v or m["standIn"].get(k) for k, v in m["map"].items()}

def inner(svg):
    parts = re.findall(r"<(?:path|circle|rect|line|polyline|polygon|ellipse)\b[^>]*?/?>", svg)
    out = []
    for el in parts:
        el = re.sub(r'\s(class|id|style|on\w+)="[^"]*"', "", el)
        if not el.endswith("/>"):
            el = el[:-1] + "/>"
        out.append(el)
    return "".join(out)

icons = {}
for ours, theirs in sorted(mapping.items()):
    f = NB / "raw" / f"{theirs}.svg"
    if f.exists():
        icons[ours] = {"src": theirs, "body": inner(f.read_text(encoding="utf-8")), "standIn": ours in m["missing"]}
(NB / "icons.json").write_text(json.dumps(icons, indent=1), encoding="utf-8")

js = """/* Headroom icon set. Artwork: Not Boring Icons (https://www.notboringicons.com), stroke style.
   Generated by tools/build_icons.py. Keys are Headroom's icon names; each maps to a Not Boring Icons name.
   Provides window.lucide.createIcons() so existing <i data-lucide="name"> markup keeps working. */
(function () {
  const ICONS = %s;
  const SKIP = new Set(['data-lucide']);
  function createIcons(opts) {
    const sw = opts && opts.attrs && opts.attrs['stroke-width'];
    document.querySelectorAll('i[data-lucide]').forEach(el => {
      const name = el.getAttribute('data-lucide'), ic = ICONS[name];
      if (!ic) return;
      const svg = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
      svg.setAttribute('xmlns', 'http://www.w3.org/2000/svg'); svg.setAttribute('width', '24'); svg.setAttribute('height', '24');
      svg.setAttribute('viewBox', '0 0 24 24'); svg.setAttribute('fill', 'none'); svg.setAttribute('stroke', 'currentColor');
      svg.setAttribute('stroke-width', sw || '1.75'); svg.setAttribute('stroke-linecap', 'round'); svg.setAttribute('stroke-linejoin', 'round');
      svg.setAttribute('aria-hidden', 'true');
      for (const a of el.attributes) if (!SKIP.has(a.name)) svg.setAttribute(a.name === 'class' ? 'class' : a.name, a.value);
      svg.setAttribute('class', ('lucide lucide-' + name + ' nbi nbi-' + ic[0] + ' ' + (el.getAttribute('class') || '')).trim());
      svg.innerHTML = ic[1];
      el.replaceWith(svg);
    });
  }
  window.HR_ICONS = ICONS;
  window.lucide = { createIcons };
})();
""" % json.dumps({k: [v["src"], v["body"]] for k, v in icons.items()}, separators=(",", ":"))
(ROOT / "site" / "icons.js").write_text(js, encoding="utf-8")
print(f"icons: {len(icons)} ({sum(v['standIn'] for v in icons.values())} stand-ins) · site/icons.js {len(js) // 1024} KB")
