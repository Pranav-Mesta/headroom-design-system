"""Pack the Headroom Figma plugin.

Reads tokens/tokens.json, the component/proof specs and the Not Boring Icons set
(figma-plugin/nbi-icons/icons.json, built by tools/build_icons.py), and writes figma-plugin/code.js (DATA + builder) and manifest.json.
Run after tools/build_tokens.py.
"""
import importlib.util, json, pathlib, re

ROOT = pathlib.Path(__file__).resolve().parent.parent
PLUG = ROOT / "figma-plugin"
t = json.loads((ROOT / "tokens" / "tokens.json").read_text(encoding="utf-8"))

def walk(d, path=""):
    for k, v in d.items():
        p = f"{path}/{k}" if path else k
        if isinstance(v, dict) and "$value" in v:
            yield p, v
        elif isinstance(v, dict):
            yield from walk(v, p)

ref = lambda x: x.strip("{}").replace("primitive.color.", "").replace(".", "/") if x.startswith("{") else x
light, dark = dict(walk(t["light"])), dict(walk(t["dark"]))
semantic = [[p, ref(v["$value"]), ref(dark[p]["$value"]), v.get("$description", "")] for p, v in light.items()]
prims = {r: {s: v["$value"] for s, v in stops.items()} for r, stops in t["primitive"]["color"].items()}
px = lambda s: float(str(s).replace("px", "").replace("ms", ""))
_sp = dict(walk(t["space"]))
_res = lambda v: px(_sp[v.strip("{}").replace("space.", "", 1).replace(".", "/")]["$value"]) if str(v).startswith("{") else px(v)
spacing = [[p, _res(v["$value"]), v.get("$description", "")] for p, v in _sp.items()]
radius = [[p, px(v["$value"]), v.get("$description", "")] for p, v in walk(t["radius"])]
size = [["size/" + p, px(v["$value"]), v.get("$description", "")] for p, v in walk(t["size"])] + [["icon/" + p, px(v["$value"]), v.get("$description", "")] for p, v in walk(t["icon"])]
types = []
for p, v in walk(t["type"]):
    val = v["$value"]
    types.append({"name": p, "size": px(val["fontSize"]), "line": px(val["lineHeight"]), "weight": val["fontWeight"],
                  "tracking": float(val["letterSpacing"].replace("em", "")), "width": val.get("fontStretch", "100%"),
                  "numeric": "fontFeatureSettings" in val, "desc": v.get("$description", "")})

def load(name):
    spec = importlib.util.spec_from_file_location(name, ROOT / "tools" / f"{name}.py")
    m = importlib.util.module_from_spec(spec); spec.loader.exec_module(m); return m
cs = load("components_spec")
pf = load("proof_spec")
comp_desc = {c["id"]: {"name": c["name"], "purpose": c["purpose"], "a11y": c["a11y"][:2], "tokens": c["tokens"]} for c in cs.COMPONENTS}
gaps = {g["name"]: g["why"] for g in pf.GAPS}

nbi = json.loads((PLUG / "nbi-icons" / "icons.json").read_text(encoding="utf-8"))
icons = {k: ('<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" '
             'stroke="#000000" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round">' + v["body"] + "</svg>") for k, v in nbi.items()}
icon_src = {k: {"src": v["src"], "standIn": v["standIn"]} for k, v in nbi.items()}

prim_names = {r: {st: v.get("$description", "") for st, v in stops.items()} for r, stops in t["primitive"]["color"].items()}
spx = load("spacing_spec"); gvs = load("governance_spec"); gds = load("guides_spec"); fls = load("flows_spec")
SPX_PX = {p_: v for p_, v, _ in spacing}
sp_groups = [{"title": g["title"], "intro": g["intro"], "tokens": [[tk[0], tk[1], SPX_PX[tk[1]], tk[2], tk[3], tk[4]] for tk in g["tokens"]]} for g in spx.GROUPS]
status = [[c["name"], gds.STATUS[c["id"]][0], gds.STATUS[c["id"]][1], gds.STATUS[c["id"]][3]] for c in cs.COMPONENTS] + [[n, "Proposed", pl, note] for n, pl, note in gds.PROPOSED]
data = {"flows": {"flows": [{"id": f["id"], "name": f["name"], "goal": f["goal"], "measure": f["measure"], "screens": [list(sc[:4]) + [[list(l) for l in sc[4]]] for sc in f["screens"]]} for f in fls.FLOWS], "proposed": [list(x) for x in fls.PROPOSED]},
        "primNames": prim_names, "spGroups": sp_groups, "spLayout": [list(l) for l in spx.LAYOUT], "spRules": spx.RULES,
        "gov": {"version": gvs.VERSION, "naming": gvs.NAMING, "semver": gvs.SEMVER, "deprecation": gvs.DEPRECATION, "contribution": gvs.CONTRIBUTION},
        "guides": {"start": gds.GETTING_STARTED, "lifecycle": gds.LIFECYCLE, "status": status, "choosers": gds.CHOOSERS, "a11y": gds.A11Y},
        "prims": prims, "semantic": semantic, "spacing": spacing, "radius": radius, "size": size, "types": types,
        "comps": comp_desc, "gaps": gaps, "icons": icons, "iconSrc": icon_src,
        "auditNote": "Light 71/71 and dark 67/67 colour usages resolve to tokens; 9/9 font sizes on scale (site/proof.html)."}
builder = (PLUG / "src" / "builder.js").read_text(encoding="utf-8") + "\n" + (PLUG / "src" / "flows.js").read_text(encoding="utf-8")
(PLUG / "code.js").write_text("// Generated by tools/build_plugin.py. Do not edit; edit figma-plugin/src/builder.js.\n"
                              "const DATA = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n" + builder, encoding="utf-8")
(PLUG / "manifest.json").write_text(json.dumps({
    "name": "Headroom DS Builder", "id": "headroom-ds-builder-local", "api": "1.0.0", "main": "code.js",
    "editorType": ["figma"], "documentAccess": "dynamic-page", "networkAccess": {"allowedDomains": ["none"], "devAllowedDomains": ["http://localhost:8766"], "reasoning": "Development only: sends board previews to a receiver on this computer for review."}
}, indent=2), encoding="utf-8")
print(f"code.js {len((PLUG / 'code.js').read_text(encoding='utf-8')) // 1024} KB · {len(icons)} icons · {len(semantic)} semantic · {len(types)} type styles")
